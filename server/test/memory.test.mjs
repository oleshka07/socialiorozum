// Збирання підказки «вже використано» з дистильованих артефактів постів.
//
// Чому саме це під тестом: раніше памʼять контенту робив LLM-виклик на кожній генерації, і його
// результат ніхто не перевіряв - «модель щось стисне». Тепер підказка збирається КОДОМ, тож зіпсувати
// її можна тихо й назавжди: загубити дедуп (і промт роздує однаковими гачками), перевищити стелю
// символів (промт і так щільний), віддати порожній заголовок без жодного пункту. Помітили б це не
// одразу, а за поступовим погіршенням постів - найгірший тип регресії.
import { test } from "node:test";
import assert from "node:assert/strict";
import { buildUsedDigest } from "../dist/memory.js";

const row = (o) => ({ hook: "", thesis: "", facts: "", cta: "", topics: "", ...o });

test("групує гачки, цифри й заклики окремими рядками", () => {
  const out = buildUsedDigest([
    row({ hook: "Ми втратили клієнта на ровному місці", facts: "40% замовлень", cta: "Напиши «кошторис»" }),
    row({ hook: "Три помилки в кошторисі", facts: "2 тижні простою" }),
  ]);
  assert.match(out, /ВЖЕ ВИКОРИСТАНО/);
  assert.match(out, /Гачки \(перші рядки\): .*ровному місці.*Три помилки/s);
  assert.match(out, /Цифри й приклади: .*40% замовлень.*2 тижні/s);
  assert.match(out, /Заклики: .*кошторис/);
});

test("дедуп ігнорує регістр і розділові - інакше промт роздувається копіями", () => {
  const out = buildUsedDigest([
    row({ hook: "А ви помічали?" }),
    row({ hook: "а ви помічали" }),
    row({ hook: "  А ВИ ПОМІЧАЛИ!!!  " }),
    row({ hook: "Інший гачок" }),
  ]);
  const hooks = out.split("\n").find((l) => l.includes("Гачки"));
  assert.equal(hooks.split(" · ").length, 2, "мало лишитись два різні гачки: " + hooks);
  assert.match(hooks, /Інший гачок/);
});

test("порожні поля не створюють порожніх пунктів і порожніх груп", () => {
  const out = buildUsedDigest([row({ hook: "Єдиний гачок", facts: "   ", cta: "" })]);
  assert.match(out, /Гачки/);
  assert.doesNotMatch(out, /Цифри/, "групи без вмісту не виводяться");
  assert.doesNotMatch(out, /Заклики/);
});

test("зовсім порожній вхід дає ПОРОЖНІЙ рядок, а не заголовок ні про що", () => {
  // інакше в промт щоразу їхав би блок «ВЖЕ ВИКОРИСТАНО:» без жодного пункту - шум, який модель
  // мусить якось інтерпретувати
  assert.equal(buildUsedDigest([]), "");
  assert.equal(buildUsedDigest([row({}), row({})]), "");
  assert.equal(buildUsedDigest([row({ hook: "   " })]), "");
});

test("тримається стелі символів навіть на великому архіві", () => {
  const many = Array.from({ length: 200 }, (_, i) => row({
    hook: "Гачок номер " + i + " ".padEnd(40, "х"),
    facts: "Цифра " + i + " ".padEnd(40, "у"),
    cta: "Заклик " + i,
  }));
  const out = buildUsedDigest(many);
  assert.ok(out.length < 1800, "підказка роздулась до " + out.length + " симв.");
  assert.match(out, /Гачки/);
});

test("бюджет ділиться між групами - цифри не витісняються гачками повністю", () => {
  // порядок груп фіксований, тож найдовші гачки могли б зʼїсти всю стелю; перевіряємо, що при
  // помірних розмірах у підказку доїжджають ВСІ три виміри
  const rows = Array.from({ length: 12 }, (_, i) => row({
    hook: "Гачок " + i, facts: "Цифра " + i, cta: "Заклик " + i,
  }));
  const out = buildUsedDigest(rows);
  assert.match(out, /Гачки/);
  assert.match(out, /Цифри й приклади/);
  assert.match(out, /Заклики/);
});
